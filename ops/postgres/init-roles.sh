#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" \
  --set=app_password="$POSTGRES_APP_PASSWORD" --set=test_password="$POSTGRES_TEST_PASSWORD" <<'SQL'
CREATE ROLE hc_app LOGIN PASSWORD :'app_password' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE hc_test LOGIN PASSWORD :'test_password' NOSUPERUSER CREATEDB NOCREATEROLE;
GRANT CONNECT ON DATABASE harborcart TO hc_app, hc_test;
GRANT USAGE ON SCHEMA public TO hc_app;
ALTER DEFAULT PRIVILEGES FOR ROLE hc_owner IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO hc_app;
ALTER DEFAULT PRIVILEGES FOR ROLE hc_owner IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO hc_app;
SQL
